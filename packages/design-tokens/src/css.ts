const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/_/g, "-").toLowerCase();
const rem = (px: number) => `${+(px / 16).toFixed(4)}rem`;
const px = (n: number) => `${n}px`;

const HEADER = `/*
 * GENERATED by packages/design-tokens/src/build-css.ts. Do not edit by hand.
 * Run: pnpm --filter @ll/design-tokens build:css
 */
`;

/** `--background`, `--muted-foreground`, `--points-text` ... (the v3 roles, shadcn names). */
function roleVarsV3(r: RolesV3, indent = "  "): string[] {
  return Object.entries(r).map(([k, v]) => `${indent}--${kebab(k)}: ${v};`);
}

/** `--ll-color-*`: aliases of the v3 roles where one exists (v2 names), values otherwise (chrome, overlay, v1 names). */
function colorVars(c: ColorRoles, indent = "  "): string[] {
  const alias = v2Alias as Record<string, string>;
  return Object.entries(c).map(([k, v]) => `${indent}--ll-color-${kebab(k)}: ${alias[k] ? `var(--${kebab(alias[k]!)})` : v};`);
}

function themeScopedVars(theme: "light" | "dark", indent = "  "): string[] {
  const out = [
    ...roleVarsV3(rolesV3[theme], indent),
    ...chartSeriesV3[theme].map((c, i) => `${indent}--chart-${i + 1}: ${c};`),
    ...colorVars(colors[theme], indent),
  ];
  // Deprecated: verticals are neutral in v2 (same values for every vertical). Kept so old class names resolve.
  for (const v of Object.values(verticalVisuals)) {
    const c = v[theme];
    const n = kebab(v.vertical);
    out.push(`${indent}--ll-vertical-${n}-accent: ${c.accent};`);
    out.push(`${indent}--ll-vertical-${n}-on-accent: ${c.onAccent};`);
    out.push(`${indent}--ll-vertical-${n}-tint: ${c.tint};`);
    out.push(`${indent}--ll-vertical-${n}-ink: ${c.ink};`);
  }
  const ch = chartColors[theme];
  ch.categorical.forEach((_, i) => out.push(`${indent}--ll-chart-${i + 1}: var(--chart-${i + 1});`));
  ch.sequential.forEach((c, i) => out.push(`${indent}--ll-chart-seq-${i + 1}: ${c};`));
  for (const k of ["line", "highlight", "you", "network", "grid", "axis"] as const) out.push(`${indent}--ll-chart-${k}: ${ch[k]};`);
  for (const [k, v] of Object.entries(ch.status)) out.push(`${indent}--ll-chart-status-${k}: ${v};`);
  for (const [k, v] of Object.entries(shadows)) {
    const css = theme === "dark" && v.css !== "none" ? shadowsDarkCss[k] ?? shadowFloatDark : v.css;
    out.push(`${indent}--ll-shadow-${k}: ${css};`);
  }
  out.push(`${indent}--ll-shadow-sheet: ${theme === "dark" ? shadowSheetDark : shadowSheet};`);
  return out;
}

function staticVars(indent = "  "): string[] {
  const out: string[] = [];
  for (const [k, v] of Object.entries(fontFamilies)) out.push(`${indent}--ll-font-${k}: ${v};`);
  for (const [k, v] of Object.entries(spacing)) out.push(`${indent}--ll-space-${String(k).replace(".", "_")}: ${rem(v)};`);
  for (const [k, v] of Object.entries(layout)) out.push(`${indent}--ll-layout-${kebab(k)}: ${px(v)};`);
  for (const [k, v] of Object.entries(radii)) out.push(`${indent}--ll-radius-${k}: ${k === "full" ? "9999px" : px(v)};`);
  out.push(`${indent}--radius: ${rem(radiusBase)};`);
  out.push(`${indent}--sidebar-width: ${rem(layout.sidebar)};`);
  out.push(`${indent}--sidebar-width-icon: ${rem(layout.rail)};`);
  for (const [k, v] of Object.entries(durations)) out.push(`${indent}--ll-duration-${k}: ${v}ms;`);
  for (const [k, v] of Object.entries(easings)) out.push(`${indent}--ll-ease-${k}: ${v};`);
  for (const [k, v] of Object.entries(zIndex)) out.push(`${indent}--ll-z-${k}: ${v};`);
  for (const [k, v] of Object.entries(touchTargets)) out.push(`${indent}--ll-touch-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(iconSizes)) out.push(`${indent}--ll-icon-${k}: ${px(v)};`);
  out.push(`${indent}--ll-icon-stroke: ${iconStroke};`);
  for (const [k, v] of Object.entries(categoryIconSizes)) out.push(`${indent}--ll-category-icon-${k}: ${px(v)};`);
  out.push(`${indent}--ll-blur-chrome: ${px(blur.chrome)};`);
  out.push(`${indent}--ll-blur-saturate: ${blur.saturate};`);
  for (const [k, v] of Object.entries(borderWidths)) out.push(`${indent}--ll-border-${kebab(k)}: ${px(v)};`);
  for (const [k, v] of Object.entries(breakpoints)) out.push(`${indent}--ll-breakpoint-${k}: ${px(v)};`);
  for (const [k, s] of Object.entries(textStyles)) {
    const n = kebab(k);
    out.push(`${indent}--ll-text-${n}-size: ${rem(s.fontSize)};`);
    out.push(`${indent}--ll-text-${n}-line-height: ${rem(s.lineHeight)};`);
    out.push(`${indent}--ll-text-${n}-weight: ${s.fontWeight};`);
    out.push(`${indent}--ll-text-${n}-tracking: ${s.letterSpacing}em;`);
    out.push(`${indent}--ll-text-${n}-family: var(--ll-font-${s.family});`);
  }
  return out;
}


/** `[data-trade="cafe"], [data-trade="bakery"] ...` for a family: every vertical of the family, so an app sets `data-trade={vertical}`. */
const tradeSelector = (f: TradeFamily, prefix = "") =>
  // With a prefix (a theme scope) the family also matches on the scope element itself (data-trade set on <html> for portalled sheets).
  verticalsByFamily(f).flatMap((v) => (prefix ? [`${prefix}[data-trade="${v}"]`, `${prefix.trim()}[data-trade="${v}"]`] : [`[data-trade="${v}"]`])).join(",\n");
/** Families that no vertical uses (never happens, but keeps the list honest) are skipped. */
const usedFamilies = () => TRADE_FAMILIES.filter((f) => verticalsByFamily(f).length > 0);

function tradeVars(f: TradeFamily, theme: "light" | "dark", indent: string): string[] {
  const c = tradeColors(f, theme);
  return [
    `${indent}--trade: ${c.accent};`,
    `${indent}--trade-foreground: ${c.foreground};`,
    `${indent}--trade-alt: ${c.alt};`,
    `${indent}--trade-soft: ${c.soft};`,
    `${indent}--trade-deep: ${c.deep};`,
  ];
}

/** Per-trade accent families (Main Street Warm). Light by default; dark follows the same switch as the roles. */
function tradeCss(): string[] {
  const out: string[] = [`/* Per-trade accent families: set data-trade="<vertical>" on the shell, pass or shop page (${usedFamilies().map((f) => `${f}: ${tradeFamilies[f].label}`).join("; ")}) */`];
  for (const f of usedFamilies()) out.push(`${tradeSelector(f)} {`, ...tradeVars(f, "light", "  "), `}`);
  out.push(``, `@media (prefers-color-scheme: dark) {`);
  for (const f of usedFamilies()) out.push(`  ${tradeSelector(f, ":root:not([data-theme=\"light\"]) ").replace(/,\n/g, ",\n  ")} {`, ...tradeVars(f, "dark", "    "), `  }`);
  out.push(`}`, ``);
  for (const f of usedFamilies()) out.push(`${tradeSelector(f, '[data-theme="dark"] ')} {`, ...tradeVars(f, "dark", "  "), `}`);
  out.push(``);
  return out;
}

export function buildTokensCss(): string {
  return [
    HEADER,
    `/* Static tokens (theme-independent) */`,
    `:root {`,
    ...staticVars(),
    `}`,
    ``,
    `/* Light theme (default) */`,
    `:root,`,
    `[data-theme="light"] {`,
    `  color-scheme: light;`,
    ...themeScopedVars("light"),
    `}`,
    ``,
    `/* Dark theme: follows the OS unless the page forces data-theme="light" */`,
    `@media (prefers-color-scheme: dark) {`,
    `  :root:not([data-theme="light"]) {`,
    `    color-scheme: dark;`,
    ...themeScopedVars("dark", "    "),
    `  }`,
    `}`,
    ``,
    `/* Dark theme: forced */`,
    `[data-theme="dark"] {`,
    `  color-scheme: dark;`,
    ...themeScopedVars("dark"),
    `}`,
    ``,
    ...tradeCss(),
  ].join("\n");
}

/** The script faces apps/web declares through next/font (packages/shared locales.ts `fonts`), each with its family name as the fallback. */
const SCRIPT_FONTS = [
  `var(--font-noto-deva, "Noto Sans Devanagari")`,
  `var(--font-noto-guru, "Noto Sans Gurmukhi")`,
  `var(--font-noto-nastaliq, "Noto Nastaliq Urdu")`,
  `var(--font-noto-naskh, "Noto Naskh Arabic")`,
].join(", ");

/**
 * v2 and v1 colour names that apps/web still uses as Tailwind classes (bg-bg, text-fg-muted, border-line, bg-brand-hover ...).
 * The final sweep grepped every other alias (v1 canvas/surface/on-* names, accent-text/soft, the per-vertical colours) and found no
 * use, so they are no longer emitted. Add a name here only when a call site needs it; the v3 names (bg-background, text-foreground,
 * border-border, bg-points ...) are always available.
 */
const ALIASES_IN_USE = new Set([
  "bg", "bg-subtle", "bg-muted", "fg", "fg-muted", "fg-subtle", "line", "line-strong", "positive", "positive-text", "negative", "location", "overlay",
  "brand", "brand-hover", "brand-pressed", "danger-subtle", "on-danger-subtle", "ring-track",
]);

export function buildThemeCss(): string {
  const out: string[] = [
    HEADER,
    `/*`,
    ` * Tailwind v4 theme for apps/web. Usage in app/globals.css:`,
    ` *   @import "tailwindcss";`,
    ` *   @import "@ll/design-tokens/theme.css";`,
    ` * Semantic colours resolve through CSS variables, so light/dark switch`,
    ` * automatically (prefers-color-scheme, or data-theme="light|dark" on <html>).`,
    ` */`,
    `@import "./tokens.css";`,
    ``,
    `@custom-variant dark {`,
    `  &:where([data-theme="dark"], [data-theme="dark"] *) {`,
    `    @slot;`,
    `  }`,
    `  @media (prefers-color-scheme: dark) {`,
    `    &:where(:root:not([data-theme="light"]), :root:not([data-theme="light"]) *) {`,
    `      @slot;`,
    `    }`,
    `  }`,
    `}`,
    ``,
    `@theme inline {`,
    `  /* Hindi, Urdu and Punjabi come after the Latin face: a glyph Inter or Bricolage lacks falls to the script's Noto face (declared with next/font in apps/web layout.tsx, which loads one only when a glyph needs it). Latin runs stay sans; no [lang] rule is needed, and a dialog that portals out of the page still gets them. */`,
    `  --font-sans: var(--font-inter, "Inter"), ${SCRIPT_FONTS}, ui-sans-serif, system-ui, -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;`,
    `  /* Fraunces for page titles, card titles and big numbers. It has no Devanagari, Gurmukhi or Arabic glyphs, so hi/ur/pa headings fall to the Noto faces at the same weight. */`,
    `  --font-display: var(--font-fraunces, "Fraunces"), ${SCRIPT_FONTS}, "Iowan Old Style", "Palatino Linotype", Georgia, serif;`,
    `  --font-wordmark: var(--font-bricolage, "Bricolage Grotesque"), var(--font-inter, "Inter"), ui-sans-serif, system-ui, sans-serif;`,
    `  --font-mono: var(--ll-font-mono);`,
    ``,
    `  /* Semantic colours (v3): bg-background, text-foreground, bg-card, bg-muted, text-muted-foreground, border-border,`,
    `   *   bg-points, text-points-text, bg-points-soft, bg-success, bg-info, bg-warning, bg-paper ... (the shadcn names).`,
    `   * v2 names (bg-bg, text-fg, border-line, text-accent-text, bg-accent-soft ...) and v1 names (canvas, surface, brand ...)`,
    `   * still resolve, as aliases. Deprecated; removed in the final sweep.`,
    `   * "accent" is shadcn's hover surface (bg-accent, text-accent-foreground), as in every shadcn component. The v2 orange is "points"`,
    `   * (bg-points, text-points-text, bg-points-soft, text-points-foreground). bg-hover / text-hover-foreground are the same surface under`,
    `   * the name the v3 call sites use. */`,
  ];
  // v3 roles. v3 names win over the v1 names that collide (success, warning, info, border, accent).
  const V3_HELD = new Set<string>();
  const v3Names = new Set<string>(["hover"]);
  for (const k of Object.keys(rolesV3.light)) {
    if (V3_HELD.has(k)) continue;
    v3Names.add(kebab(k));
    out.push(`  --color-${kebab(k)}: var(--${kebab(k)});`);
  }
  out.push(`  --color-hover: var(--accent);`, `  --color-hover-foreground: var(--accent-foreground);`);
  out.push(``, `  /* v2 and v1 names (aliases). Only the names a call site in apps/web still uses are emitted (ALIASES_IN_USE); every other v2 and v1`);
  out.push(`   * Tailwind name was proven unused by grep in the v3 final sweep and removed. TS roles and the --ll-color-* variables are unchanged. */`);
  for (const k of Object.keys(colors.light)) if (!v3Names.has(kebab(k)) && ALIASES_IN_USE.has(kebab(k))) out.push(`  --color-${kebab(k)}: var(--ll-color-${kebab(k)});`);
  out.push(``, `  /* Charts */`);
  chartSeriesV3.light.forEach((_, i) => out.push(`  --color-chart-${i + 1}: var(--chart-${i + 1});`));
  chartColors.light.sequential.forEach((_, i) => out.push(`  --color-chart-seq-${i + 1}: var(--ll-chart-seq-${i + 1});`));
  for (const k of ["line", "highlight", "you", "network", "grid", "axis", "status-low", "status-building", "status-healthy"]) {
    out.push(`  --color-chart-${k}: var(--ll-chart-${k});`);
  }
  out.push(``, `  /* Elevation: shadow-float is the only v2 shadow (switches in dark mode). sm = none; md/lg/xl = float (deprecated). */`);
  for (const k of Object.keys(shadows)) out.push(`  --shadow-${k}: var(--ll-shadow-${k});`);
  out.push(`  --shadow-sheet: var(--ll-shadow-sheet);`);
  out.push(``, `  /* Radii (v3): rounded-sm 6, md 8, lg 10 (= rounded-input), xl 14, 2xl 18 (shadcn calc from --radius); rounded-card 16, rounded-sheet 24 */`);
  out.push(`  --radius-sm: calc(var(--radius) - 4px);`, `  --radius-md: calc(var(--radius) - 2px);`, `  --radius-lg: var(--radius);`);
  out.push(`  --radius-xl: calc(var(--radius) + 4px);`, `  --radius-2xl: calc(var(--radius) + 8px);`, `  --radius-3xl: calc(var(--radius) + 12px);`, `  --radius-4xl: calc(var(--radius) + 16px);`);
  out.push(`  --radius-input: ${px(radii.input)};`, `  --radius-card: ${px(radii.card)};`, `  --radius-sheet: ${px(radii.sheet)};`, `  --radius-tile: ${px(radii.tile)};`);
  out.push(`}`, ``);

  out.push(`@theme {`);
  out.push(`  /* Raw palette for marketing / illustration only (ll- prefix so Tailwind's own scales are untouched): bg-ll-gray-950, text-ll-orange-700 ... */`);
  for (const [name, scale] of Object.entries(palette)) {
    for (const [step, hex] of Object.entries(scale)) out.push(`  --color-ll-${name}-${kebab(step)}: ${hex};`);
  }
  out.push(``, `  /* Type scale (v2): text-caption 11, text-meta 13, text-body 15, text-headline 17, text-title 22, text-large-title 28, text-display-number 40.`);
  out.push(`   * Pair display styles with font-display (and lowercase for map/category labels). */`);
  for (const [k, s] of Object.entries(textStyles)) {
    const n = kebab(k);
    out.push(`  --text-${n}: ${rem(s.fontSize)};`);
    out.push(`  --text-${n}--line-height: ${rem(s.lineHeight)};`);
    out.push(`  --text-${n}--font-weight: ${s.fontWeight};`);
    if (s.letterSpacing !== 0) out.push(`  --text-${n}--letter-spacing: ${s.letterSpacing}em;`);
  }
  out.push(``, `  /* Motion: ease-out (taps, ${durations.tap}ms), ease-sheet (sheets, ${durations.sheet}ms) */`);
  for (const [k, v] of Object.entries(easings)) out.push(`  --ease-${k}: ${v};`);
  out.push(``, `  /* Frosted map chrome: backdrop-blur-chrome */`);
  out.push(`  --blur-chrome: ${px(blur.chrome)};`);
  out.push(``, `  /* Breakpoints (Tailwind defaults, restated so they are owned here) */`);
  for (const [k, v] of Object.entries(breakpoints)) out.push(`  --breakpoint-${k}: ${rem(v)};`);
  out.push(``, `  --spacing: 0.25rem;`);
  out.push(``, `  /* Animations */`);
  out.push(`  --animate-shimmer: ll-shimmer 1.4s linear infinite;`);
  out.push(`  --animate-stamp-pop: ll-stamp-pop ${durations.sheet}ms ${easings.out} both;`);
  out.push(`  --animate-fade-in: ll-fade-in ${durations.tap}ms ${easings.out} both;`);
  out.push(`  --animate-sheet-up: ll-sheet-up ${durations.sheet}ms ${easings.sheet} both;`);
  out.push(``);
  out.push(`  @keyframes ll-shimmer {`);
  out.push(`    0% { background-position: -200% 0; }`);
  out.push(`    100% { background-position: 200% 0; }`);
  out.push(`  }`);
  out.push(`  @keyframes ll-stamp-pop {`);
  out.push(`    0% { transform: scale(0.4); opacity: 0; }`);
  out.push(`    60% { transform: scale(1.12); opacity: 1; }`);
  out.push(`    100% { transform: scale(1); opacity: 1; }`);
  out.push(`  }`);
  out.push(`  @keyframes ll-fade-in {`);
  out.push(`    from { opacity: 0; }`);
  out.push(`    to { opacity: 1; }`);
  out.push(`  }`);
  out.push(`  @keyframes ll-sheet-up {`);
  out.push(`    from { transform: translateY(100%); }`);
  out.push(`    to { transform: translateY(0); }`);
  out.push(`  }`);
  out.push(`}`, ``);

  out.push(
    `/* Utilities */`,
    `@utility chrome {`,
    `  /* Frosted capsule over the map: tab bar, top capsules. Map chrome ONLY. */`,
    `  background-color: var(--ll-color-chrome);`,
    `  -webkit-backdrop-filter: blur(var(--ll-blur-chrome)) saturate(var(--ll-blur-saturate));`,
    `  backdrop-filter: blur(var(--ll-blur-chrome)) saturate(var(--ll-blur-saturate));`,
    `  box-shadow: var(--ll-shadow-float);`,
    `}`,
    `@utility hairline {`,
    `  border: var(--ll-border-hairline) solid var(--ll-color-line);`,
    `}`,
    `@utility tabular {`,
    `  font-variant-numeric: tabular-nums;`,
    `}`,
    `@utility touch-target {`,
    `  min-height: var(--ll-touch-default);`,
    `  min-width: var(--ll-touch-default);`,
    `}`,
    `@utility touch-target-counter {`,
    `  min-height: var(--ll-touch-counter);`,
    `  min-width: var(--ll-touch-counter);`,
    `}`,
    `@utility touch-target-kiosk {`,
    `  min-height: var(--ll-touch-kiosk);`,
    `  min-width: var(--ll-touch-kiosk);`,
    `}`,
    `@utility focus-ring {`,
    `  outline: var(--ll-border-focus) solid var(--ll-color-focus-ring);`,
    `  outline-offset: var(--ll-border-focus-offset);`,
    `}`,
    `@utility skeleton {`,
    `  background-color: var(--ll-color-skeleton);`,
    `  background-image: linear-gradient(90deg, var(--ll-color-skeleton) 0%, var(--ll-color-skeleton-highlight) 50%, var(--ll-color-skeleton) 100%);`,
    `  background-size: 200% 100%;`,
    `  animation: ll-shimmer 1.4s linear infinite;`,
    `  @media (prefers-reduced-motion: reduce) {`,
    `    animation: none;`,
    `  }`,
    `}`,
    `@utility z-banner {`,
    `  z-index: var(--ll-z-banner);`,
    `}`,
    `@utility z-modal {`,
    `  z-index: var(--ll-z-modal);`,
    `}`,
    `@utility z-toast {`,
    `  z-index: var(--ll-z-toast);`,
    `}`,
    `@utility z-sticky {`,
    `  z-index: var(--ll-z-sticky);`,
    `}`,
    `@utility z-overlay {`,
    `  z-index: var(--ll-z-overlay);`,
    `}`,
    `@utility z-popover {`,
    `  z-index: var(--ll-z-popover);`,
    `}`,
    ``,
    `@layer base {`,
    `  html {`,
    `    background-color: var(--ll-color-bg);`,
    `    color: var(--ll-color-fg);`,
    `    font-variant-numeric: tabular-nums;`,
    `    -webkit-font-smoothing: antialiased;`,
    `    -moz-osx-font-smoothing: grayscale;`,
    `    -webkit-text-size-adjust: 100%;`,
    `  }`,
    `  :focus-visible {`,
    `    outline: var(--ll-border-focus) solid var(--ll-color-focus-ring);`,
    `    outline-offset: var(--ll-border-focus-offset);`,
    `  }`,
    `  @media (prefers-reduced-motion: reduce) {`,
    `    *, *::before, *::after {`,
    `      animation-duration: 1ms !important;`,
    `      animation-iteration-count: 1 !important;`,
    `      transition-duration: 1ms !important;`,
    `      scroll-behavior: auto !important;`,
    `    }`,
    `  }`,
    `}`,
    ``,
  );
  return out.join("\n");
}
