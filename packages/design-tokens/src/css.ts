function clearCss(): string[] {
  const solid = (t: "light" | "dark") => {
    const { toastBg, ...g } = clearGlassSolid[t];
    return [...glassVars(g, "    "), `    --toast-bg: ${toastBg};`];
  };
  const tL = clearTradeColors("terracotta", "light");
  const tD = clearTradeColors("terracotta", "dark");
  const out: string[] = [
    `/* ===== Clear (v3.2, Liquid Glass chrome over a flat content layer). Light only by default; dark only with data-theme="dark". ===== */`,
    `${CLEAR_LIGHT} {`,
    ...clearScopedVars("light"),
    `  --trade-tint: ${tL.soft};`,
    `  --trade-nav: ${tL.nav};`,
    `}`,
    ``,
    `${CLEAR_DARK} {`,
    ...clearScopedVars("dark"),
    `  --trade-tint: ${tD.soft};`,
    `  --trade-nav: ${tD.nav};`,
    `}`,
    ``,
    `/* Clear static: radii, Inter with display optical sizing, the Polaris-dense type scale on the 4px grid (audit 2.5). */`,
    `:root[data-theme-style="clear"] {`,
    `  --ll-radius-card: ${clearLayout.card.radius}px;`,
    `  --ll-radius-sheet: ${clearLayout.radius.r9}px;`,
    `  --ll-radius-tile: ${clearLayout.radius.r6}px;`,
    `  --ll-face-display: ${SANS_STACK};`,
    `  --ll-face-wordmark: ${SANS_STACK};`,
    ...Object.entries(CLEAR_TYPE).flatMap(([k, [size, lh, w, ls]]) => [
      `  --text-${kebab(k)}: ${rem(size)};`,
      `  --text-${kebab(k)}--line-height: ${rem(lh)};`,
      `  --text-${kebab(k)}--font-weight: ${w};`,
      ...(ls !== undefined ? [`  --text-${kebab(k)}--letter-spacing: ${ls}em;`] : []),
    ]),
    `}`,
    ``,
    `/* Reduce Transparency: opaque glass, no blur or rim sheen (same layout). The .solid class forces it. */`,
    `@media (prefers-reduced-transparency: reduce) {`,
    `  :root[data-theme-style="clear"] {`,
    ...solid("light"),
    `  }`,
    `  :root[data-theme-style="clear"][data-theme="dark"] {`,
    ...solid("dark"),
    `  }`,
    `}`,
    `:root[data-theme-style="clear"].solid {`,
    ...solid("light").map((l) => l.slice(2)),
    `}`,
    `:root[data-theme-style="clear"][data-theme="dark"].solid {`,
    ...solid("dark").map((l) => l.slice(2)),
    `}`,
    ``,
    `/* Clear trade accents: the active nav item, icon tiles and the chart's current bar only. */`,
  ];
  for (const f of usedFamilies()) out.push(`${clearTradeSelector(f, "light")} {`, ...clearTradeVars(f, "light", "  "), `}`);
  for (const f of usedFamilies()) out.push(`${clearTradeSelector(f, "dark")} {`, ...clearTradeVars(f, "dark", "  "), `}`);
  out.push(``);
  return out;
}

export function buildTokensCss(): string {
  return [
    HEADER,
    `/* Static tokens (theme-independent) */`,
    `:root {`,
    ...staticVars(),
    `}`,
    ``,
    `/* Light theme (default) */`,
    `:root,`,
    `[data-theme="light"] {`,
    `  color-scheme: light;`,
    ...themeScopedVars("light"),
    ...warmExtraVars("light", "  "),
    `  --trade-tint: var(--trade-soft);`,
    `  --trade-nav: var(--sidebar-accent);`,
    `}`,
    ``,
    `/* Dark theme: follows the OS unless the page forces data-theme="light" */`,
    `@media (prefers-color-scheme: dark) {`,
    `  :root:not([data-theme="light"]) {`,
    `    color-scheme: dark;`,
    ...themeScopedVars("dark", "    "),
    ...warmExtraVars("dark", "    "),
    `  }`,
    `}`,
    ``,
    `/* Dark theme: forced */`,
    `[data-theme="dark"] {`,
    `  color-scheme: dark;`,
    ...themeScopedVars("dark"),
    ...warmExtraVars("dark", "  "),
    `}`,
    ``,
    ...tradeCss(),
    ...clearCss(),
  ].join("\n");
}

