/** Selector for a Clear light scope: the root, a forced-light island inside a Clear page, and an element carrying both attributes. */
const CLEAR_LIGHT = `:root[data-theme-style="clear"],\n[data-theme-style="clear"] [data-theme="light"],\n[data-theme-style="clear"][data-theme="light"]`;
/** Clear dark is opt-in only: data-theme="dark" set from the shop setting. prefers-color-scheme never turns it on. */
const CLEAR_DARK = `:root[data-theme-style="clear"][data-theme="dark"],\n[data-theme-style="clear"][data-theme="dark"],\n[data-theme-style="clear"] [data-theme="dark"]`;

/** Tailwind colour names for the Clear-only roles: bg-link, text-link, border-border-strong, bg-lg-lift, bg-trade-tint ... */
export const CLEAR_COLOR_NAMES = [
  "link", "primary-hover", "border-strong", "success-soft", "warning-soft", "destructive-text", "destructive-soft", "row-sel", "tile", "chart-muted", "chart-hi",
  "scrim", "toast-bg", "toast-fg", "trade-tint", "trade-nav", "lg-fill", "lg-fill-side", "lg-fill-strong", "lg-lift", "lg-edge", "lg-seg-track",
] as const;

function extraVars(e: ClearExtraRoles, indent: string): string[] {
  return Object.entries(e).map(([k, v]) => `${indent}--${kebab(k)}: ${v};`);
}
function glassVars(g: Partial<Record<keyof GlassRoles, string | number>>, indent: string): string[] {
  const out: string[] = [];
  for (const [k, v] of Object.entries(g)) {
    if (k === "shadowCard") out.push(`${indent}--ll-shadow-card: ${v};`);
    else out.push(`${indent}--lg-${kebab(k)}: ${typeof v === "number" && k.startsWith("blur") ? `${v}px` : v};`);
  }
  return out;
}

/** Warm has no glass: the --lg-* roles and the Clear-only roles resolve to opaque Warm values, so a Clear class used under Warm degrades to solid. */
function warmExtraVars(theme: "light" | "dark", indent: string): string[] {
  const r = rolesV3[theme];
  const e: ClearExtraRoles = {
    link: r.primaryText,
    primaryHover: r.primary,
    borderStrong: r.sidebarBorder,
    successSoft: r.muted,
    warningSoft: r.muted,
    destructiveText: r.destructive,
    destructiveSoft: r.muted,
    rowSel: r.accent,
    tile: r.muted,
    chartMuted: r.border,
    chartHi: r.primary,
    scrim: theme === "light" ? "rgba(42, 30, 20, 0.42)" : "rgba(10, 6, 3, 0.62)",
    toastBg: r.foreground,
    toastFg: r.background,
  };
  const g = {
    fill: r.card, fillSide: r.sidebar, fillStrong: r.card, lift: r.sidebarAccent, rimA: "transparent", rimB: "transparent", rimC: "transparent",
    edge: r.border, inner: "transparent", shadow: "none", shadowLg: "none", blur: 0, blurStrong: 0, sat: 1, segTrack: r.muted,
  };
  return [...extraVars(e, indent), ...glassVars(g, indent)];
}

function clearScopedVars(theme: "light" | "dark", indent = "  "): string[] {
  const r = clearRoles[theme];
  return [
    `${indent}color-scheme: ${theme};`,
    ...roleVarsV3(r, indent),
    // Charts: monochrome; the current bar is the trade colour (--chart-hi) and the rest --chart-muted.
    ...[r.foreground, clearExtra[theme].chartMuted, r.mutedForeground, r.info, r.success].map((c, i) => `${indent}--chart-${i + 1}: ${c};`),
    ...extraVars(clearExtra[theme], indent),
    ...glassVars(clearGlass[theme], indent),
    `${indent}--ll-shadow-sheet: ${clearGlass[theme].shadowLg};`,
    `${indent}--ll-color-chrome: ${clearGlass[theme].fill};`,
    `${indent}--ll-color-overlay: ${clearExtra[theme].scrim};`,
    `${indent}--ll-color-focus-ring: ${r.ring};`,
    // Loading skeletons: Clear's muted fill with a card-coloured shimmer (Warm's sand tones showed through under Clear before).
    `${indent}--ll-color-skeleton: ${r.muted};`,
    `${indent}--ll-color-skeleton-highlight: ${r.card};`,
  ];
}

const clearTradeSelector = (f: TradeFamily, theme: "light" | "dark") => {
  const scope = theme === "light" ? `:root[data-theme-style="clear"]` : `:root[data-theme-style="clear"][data-theme="dark"]`;
  return verticalsByFamily(f).flatMap((v) => [`${scope} [data-trade="${v}"]`, `${scope}[data-trade="${v}"]`]).join(",\n");
};

function clearTradeVars(f: TradeFamily, theme: "light" | "dark", indent: string): string[] {
  const c = clearTradeColors(f, theme);
  return [
    `${indent}--trade: ${c.accent};`,
    `${indent}--trade-foreground: ${c.foreground};`,
    `${indent}--trade-alt: ${c.alt};`,
    `${indent}--trade-soft: ${c.soft};`,
    `${indent}--trade-deep: ${c.deep};`,
    `${indent}--trade-tint: ${c.soft};`,
    `${indent}--trade-nav: ${c.nav};`,
    `${indent}--chart-hi: ${c.accent};`,
    `${indent}--trade-pass-from: ${c.passFrom};`,
    `${indent}--trade-pass-to: ${c.passTo};`,
    `${indent}--trade-pass-text: ${c.passText};`,
  ];
}

