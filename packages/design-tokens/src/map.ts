/** Layer roles we restyle. */
export type MapLayerRole =
  | "background"
  | "water"
  | "waterway"
  | "park"
  | "landuse"
  | "building"
  | "roadCasing"
  | "roadMajor"
  | "roadMinor"
  | "path"
  | "rail"
  | "boundary"
  | "streetLabel"
  | "waterLabel"
  | "placeLabel"
  | "hidden";

interface LayerLike {
  id: string;
  type: string;
  "source-layer"?: string;
  paint?: Record<string, unknown>;
  layout?: Record<string, unknown>;
  [k: string]: unknown;
}

/** Classify an OpenMapTiles-schema layer (positron, liberty, bright…). */
export function mapLayerRole(l: LayerLike): MapLayerRole | null {
  const id = l.id.toLowerCase();
  const src = (l["source-layer"] ?? "").toLowerCase();
  if (l.type === "background") return "background";
  if (l.type === "symbol") {
    if (src === "poi" || /(^|[_-])poi([_-]|$)|aerodrome|airport|housenum|shield|mountain_peak|aeroway/.test(`${id} ${src}`)) return "hidden";
    if (src === "transportation_name" || /highway-name|road.*label|street/.test(id)) return "streetLabel";
    if (/water/.test(`${id} ${src}`)) return "waterLabel";
    return "placeLabel";
  }
  if (src === "water" || /^water$|ocean|lake/.test(id)) return l.type === "fill" ? "water" : null;
  if (src === "waterway") return "waterway";
  if (/ice_shelf|glacier|sand/.test(id)) return "landuse";
  if (src === "park" || /park|wood|grass|cemetery|landcover/.test(id)) return "park";
  if (src === "landuse" || src === "aeroway") return l.type === "fill" ? "landuse" : "roadMinor";
  if (src === "building") return "building";
  if (src === "boundary") return "boundary";
  if (src === "transportation" || /road|highway|bridge|tunnel/.test(id)) {
    if (/rail/.test(id)) return /dash/.test(id) ? "path" : "rail";
    if (/casing/.test(id)) return "roadCasing";
    if (/path|pier|track/.test(id)) return "path";
    if (/motorway|major|trunk|primary/.test(id)) return "roadMajor";
    return "roadMinor";
  }
  return null;
}

/** Paint/layout overrides per role, as plain data (also emitted to map/corner-*.json). */
export function cornerMapOverrides(mode: MapMode) {
  const c = cornerMapPalette[mode];
  const labelHalo = { "text-halo-color": c.labelHalo, "text-halo-width": 1.25, "text-halo-blur": 0 };
  return {
    name: `corner-${mode}`,
    mode,
    base: MAP_BASE_STYLE_URL,
    palette: c,
    roles: {
      background: { paint: { "background-color": c.land } },
      water: { paint: { "fill-color": c.water, "fill-outline-color": c.water } },
      waterway: { paint: { "line-color": c.waterway } },
      park: { paint: { "fill-color": c.park, "fill-opacity": 1 } },
      landuse: { paint: { "fill-color": c.landuse } },
      building: { paint: { "fill-color": c.building, "fill-outline-color": c.buildingOutline } },
      roadCasing: { paint: { "line-color": c.roadCasing } },
      roadMajor: { paint: { "line-color": c.roadMajor } },
      roadMinor: { paint: { "line-color": c.roadMinor, "line-opacity": 1 } },
      path: { paint: { "line-color": c.path } },
      rail: { paint: { "line-color": c.rail } },
      boundary: { paint: { "line-color": c.boundary } },
      streetLabel: {
        paint: { "text-color": c.streetLabel, ...labelHalo },
        layout: { "text-size": ["interpolate", ["linear"], ["zoom"], 13, 10, 17, 12] },
      },
      waterLabel: { paint: { "text-color": c.waterLabel, ...labelHalo }, layout: { "text-size": 11 } },
      placeLabel: { paint: { "text-color": c.placeLabel, ...labelHalo } },
      hidden: { layout: { visibility: "none" } },
    } satisfies Record<MapLayerRole, { paint?: Record<string, unknown>; layout?: Record<string, unknown> }>,
  };
}

/** Paint/layout keys valid per layer type (so we never set fill-* on a line layer). */
const prefixFor: Record<string, string> = { background: "background-", fill: "fill-", line: "line-", symbol: "text-" };

function pick(obj: Record<string, unknown> | undefined, prefix: string | undefined): Record<string, unknown> {
  if (!obj || !prefix) return {};
  return Object.fromEntries(Object.entries(obj).filter(([k]) => k.startsWith(prefix)));
}

/**
 * Take a MapLibre style JSON (OpenFreeMap positron by default) and return a
 * NEW style with the Corner look. Pure; does not mutate the input.
 */
export function cornerMapStyle<S extends { layers?: LayerLike[] }>(baseStyleJson: S, mode: MapMode = "light"): S {
  const { roles } = cornerMapOverrides(mode);
  const layers = (baseStyleJson.layers ?? []).map((l) => {
    const role = mapLayerRole(l);
    if (!role) return { ...l };
    const o = roles[role] as { paint?: Record<string, unknown>; layout?: Record<string, unknown> };
    if (role === "hidden") return { ...l, layout: { ...(l.layout ?? {}), visibility: "none" } };
    const paint = { ...(l.paint ?? {}), ...pick(o.paint, prefixFor[l.type]) };
    // A layer's own text-size is kept unless we explicitly shrink it (street / water labels).
    const layout = o.layout ? { ...(l.layout ?? {}), ...o.layout } : l.layout;
    return layout ? { ...l, paint, layout } : { ...l, paint };
  });
  return { ...baseStyleJson, name: `corner-${mode}`, layers } as S;
}

/** Google Maps JSON style element (react-native-maps `customMapStyle`). */
export interface GoogleMapStyler {
  featureType?: string;
  elementType?: string;
  stylers: Record<string, string | number>[];
}

