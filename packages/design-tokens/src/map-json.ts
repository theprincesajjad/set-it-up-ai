import { cornerMapOverrides, type MapMode } from "./map.js";

/** Serialised map overrides for map/corner-<mode>.json (pure; used by build + test). */
export function buildMapJson(mode: MapMode): string {
  const o = cornerMapOverrides(mode);
  return `${JSON.stringify(
    {
      $comment: "GENERATED by packages/design-tokens/src/build-css.ts from src/map.ts. Apply with cornerMapStyle(baseStyle, mode). Roles are matched by mapLayerRole() on OpenMapTiles-schema styles (OpenFreeMap positron).",
      ...o,
    },
    null,
    2,
  )}\n`;
}
