export type EarnType = "per_dollar" | "per_visit" | "stamps";

export interface ProgramTemplate {
  label: string;
  earnType: EarnType;
  pointsPerDollar: number;
  pointsPerVisit: number;
  /** For stamp programs: stamps needed for the reward. */
  stampGoal: number;
  terminology: "points" | "stamps" | "stars";
  welcomeBonus: number;
  rewards: { name: string; pointsCost: number; rewardType: RewardType; value: number }[];
  /** Merchant categories created at setup; earnEligible=false means no points. */
  categories: { name: string; earnEligible: boolean; discountEligible: boolean }[];
  discountCard?: { name: string; percentOff: number; terms: string };
  /** The paid plan this vertical is most likely to need later. */
  upsellPlan: "plus" | "pro";
}

export type RewardType = "amount_off" | "percent_off" | "free_item" | "custom";

