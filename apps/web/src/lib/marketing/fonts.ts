import localFont from "next/font/local";

/**
 * The marketing text face (wave V, direction B): Schibsted Grotesk (Schibsted / Bakken & Bæck, SIL OFL 1.1,
 * ./fonts/SchibstedGrotesk-OFL.txt), for the landing page's text, the marketing header and footer and the wordmark. It feeds
 * `--mkt-face-sans` and `--mkt-face-display` (@ll/design-tokens marketing.ts) inside the wrappers that carry `marketingFontVars` and
 * the `.mkt` class, so app screens keep their faces. hi, ur and pa text falls through to Noto.
 *
 * Wave W: self-hosted so every marketing page gets the same file, preloaded, in `font-display: block`: the header is the first thing
 * drawn on every marketing page and the home page's lede is its largest paint on phones, so text waits the few hundred ms for the face
 * instead of flashing Arial. One variable file (weights 400 to 800, the range the marketing pages set), subset with fontTools to Basic
 * Latin, the accented Latin-1 letters of French and Spanish names, and the punctuation the copy uses (’ “ ” · – — … • → €), no
 * hinting: 29 kB. The fallback face is Arial sized to Schibsted's metrics (size-adjust and ascent/descent overrides, generated by
 * next/font), so an edge case past the block period never shifts the layout. The source and the subset command are in the wave W
 * notes (scratchpad tools/subset.sh); re-run them to add characters.
 */
const sans = localFont({
  src: [{ path: "./fonts/schibsted-grotesk.woff2", weight: "400 800", style: "normal" }],
  variable: "--font-mkt-sans",
  display: "block",
  fallback: ["Arial", "Helvetica", "sans-serif"],
  adjustFontFallback: "Arial",
  preload: true,
});

export const marketingFontVars = sans.variable;

/**
 * Wave W2: the root layout's skip link ("Skip to content", `.ll-skip`) sits outside every `.mkt` wrapper, so it would draw in Inter,
 * which the home page does not otherwise load. The marketing layouts render this rule in a hoisted <style> (React dedupes it by href),
 * so on marketing pages it uses the face they already preload; app pages keep Inter.
 */
export const marketingSkipLinkCss = `.ll-skip{font-family:${sans.style.fontFamily}}`;
